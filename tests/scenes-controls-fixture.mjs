import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { SECOND_GRADIENT } from './scenes-fixtures.mjs';
const require = createRequire(import.meta.url);
const { SECTIONS } = require('../settings-nav.js');
const read = name => fs.readFileSync(new URL(`../${name}`, import.meta.url), 'utf8');

// A structural preflight, not a substitute for native rendering/actionability.
// Read the real HTML controls and exported navigation metadata, so the fixture
// cannot silently invent a section, control type, option or gradient preset.
function htmlControls(html) {
  const nodes = [], markup = html.replace(/<!--[\s\S]*?-->/g, '');
  let section = null;
  for (const tag of markup.matchAll(/<([a-z][\w-]*)\b([^<>]*?)>/gi)) {
    const attrs = Object.fromEntries([...tag[2].matchAll(/([\w:-]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g)].map(match => [match[1], match[2] ?? match[3] ?? match[4] ?? '']));
    if (attrs['data-settings-section']) section = attrs['data-settings-section'];
    const node = { tag: tag[1].toLowerCase(), attrs, section };
    if (node.tag === 'select') {
      const body = markup.slice(tag.index + tag[0].length, markup.indexOf('</select>', tag.index));
      node.options = [...body.matchAll(/<option\b[^>]*\bvalue="([^"]*)"/g)].map(match => match[1]);
    }
    nodes.push(node);
  }
  return nodes;
}
const hasClass = (node, value) => (node.attrs.class || '').split(/\s+/).includes(value);
export function verifySceneControlFixture(suite = read('tests/scenes.test.mjs')) {
  const home = htmlControls(read('home.html')), popup = htmlControls(read('popup.html'));
  const nodes = home.concat(popup), sections = new Set(SECTIONS.map(section => section.id));
  const ids = new Set(nodes.map(node => node.attrs.id).filter(Boolean));
  for (const section of SECTIONS) {
    assert.ok(home.some(node => node.attrs['data-settings-section'] === section.id), `${section.id}: real settings content exists`);
    // These IDs are generated by settings-nav.buildNav, not literal home HTML.
    ids.add(`settings-nav-${section.id}`);
  }
  for (const file of ['home.js', 'folders.js', 'command-palette.js', 'scene-runtime.js']) {
    const source = read(file);
    for (const match of source.matchAll(/\b(\w+)\.id\s*=\s*['"]([\w-]+)['"]/g)) {
      ids.add(match[2]);
      const creation = [...source.slice(0, match.index).matchAll(new RegExp(`(?:const|let)\\s+${match[1]}\\s*=\\s*document\\.createElement\\(['"](\\w+)['"]\\)`, 'g'))].at(-1);
      if (creation) {
        const body = source.slice(creation.index, match.index);
        const type = body.match(new RegExp(`${match[1]}\\.type\\s*=\\s*['"]([^'"]+)['"]`))?.[1];
        nodes.push({ tag: creation[1], attrs: { id: match[2], ...(type ? { type } : {}) } });
      }
    }
    for (const node of htmlControls(source)) if (node.attrs.id) { ids.add(node.attrs.id); nodes.push(node); }
  }
  for (const match of suite.matchAll(/\bsettings\(['"]([^'"]+)['"]/g)) assert.ok(sections.has(match[1]), `unknown settings section: ${match[1]}`);
  for (const match of suite.matchAll(/#([a-z][\w-]*)/gi)) {
    if (match[1] === 'settings-nav-') continue; // The helper interpolates a validated SECTIONS entry.
    assert.ok(ids.has(match[1]), `unknown native selector: #${match[1]}`);
  }
  for (const match of suite.matchAll(/\.locator\((['"])(#[\w-]+)\1\)\.(selectOption|check|uncheck|setInputFiles|fill)\(([^)]*)\)/g)) {
    const [, , selector, operation, argument] = match;
    const candidates = nodes.filter(node => node.attrs.id === selector.slice(1));
    assert.ok(candidates.length, `${selector}: control must exist in the actual HTML`);
    const accepts = node => operation === 'selectOption' ? node.tag === 'select'
      : operation === 'setInputFiles' ? node.tag === 'input' && node.attrs.type === 'file'
        : ['check', 'uncheck'].includes(operation) ? node.tag === 'input' && ['checkbox', 'radio'].includes(node.attrs.type)
          : node.tag === 'textarea' || node.tag === 'input' && !['checkbox', 'radio', 'range', 'file'].includes(node.attrs.type);
    assert.ok(candidates.some(accepts), `${selector}: native ${operation} requires the correct control type`);
    const option = argument.match(/^['"]([^'"]+)['"]$/)?.[1];
    if (operation === 'selectOption' && option && candidates.some(node => node.options?.length)) {
      assert.ok(candidates.some(node => node.options?.includes(option)), `${selector}: nonexistent option ${option}`);
    }
  }
  for (const [className, attribute] of [['layout-size-preset', 'data-size'], ['tab-btn', 'data-type'], ['theme-mode-tab', 'data-theme']]) {
    const selector = new RegExp(`\\.${className}\\[${attribute}="([^"$]+)"\\]`, 'g');
    for (const match of suite.matchAll(selector)) assert.ok(home.some(node => hasClass(node, className) && node.attrs[attribute] === match[1]), `nonexistent preset: ${match[0]}`);
  }
  const preset = home.find(node => hasClass(node, 'preset-item') && node.attrs['data-value'] === SECOND_GRADIENT);
  assert.ok(preset, 'SECOND_GRADIENT is an exact native preset value');
  assert.equal(preset.attrs['data-bg'], 'gradient'); assert.equal(preset.section, 'wallpaper');
  for (const id of ['layout-columns', 'layout-show-names', 'layout-max-width', 'todo-button-visible']) assert.equal(home.find(node => node.attrs.id === id)?.section, 'shortcuts', `${id}: navigate to its actual section`);
  const width = home.find(node => node.attrs.id === 'layout-max-width');
  assert.equal(width.attrs.type, 'range'); assert.equal(width.attrs.min, '640'); assert.equal(width.attrs.step, '20');
  const language = home.find(node => node.attrs.id === 'language-preference');
  assert.equal(language.section, 'appearance'); assert.ok(['en', 'zh-CN'].every(value => language.options.includes(value)));
  assert.ok(['light', 'dark'].every(value => home.some(node => hasClass(node, 'theme-mode-tab') && node.attrs['data-theme'] === value)));
  return { sections: sections.size, checkedIds: new Set([...suite.matchAll(/#([a-z][\w-]*)/gi)].map(match => match[1]).filter(id => id !== 'settings-nav-')).size };
}
